"""End-to-End Integration Test for Project Doppler-Geo.

Simulates a full realistic scenario:
- A secret ground observer at (40.0000, -75.0000) with microphone.
- Two distinct propeller aircraft flying overhead at different times and headings.
- Synthetic audio containing the Doppler shifts generated by the physical trajectories.
- Massive ADSB flight parquet log with distractor flights and jet engines.
- DopplerGeoPipeline runs Phases 1 through 6 to locate the secret ground observer.
"""

import os
import pytest
import numpy as np
import pandas as pd
import soundfile as sf

from doppler_geo.phase1_ingestion import BoundingBox, SyntheticDEMHandler
from doppler_geo.phase2_audio import (
    AudioEventMeasurement,
    MeasurementConfig,
    SpectrogramGenerator,
)
from doppler_geo.phase4_physics.doppler_modeler import DopplerModeler
from doppler_geo.phase4_physics.trajectory_spline import TrajectorySpline
from doppler_geo.phase6_refinement import DopplerGeoPipeline


from doppler_geo.simulation import create_simulation_data


@pytest.fixture
def synthetic_simulation_environment(tmp_path):
    return create_simulation_data(tmp_path)


def test_full_pipeline_end_to_end(synthetic_simulation_environment, tmp_path):
    """Run complete pipeline and verify recovery of true ground location."""
    env = synthetic_simulation_environment
    out_dir = str(tmp_path / "pipeline_output")

    pipeline = DopplerGeoPipeline(
        dem_handler=env["dem"],
        coarse_resolution_m=100.0,
        micro_resolution_m=15.0,
        micro_radius_m=200.0,
        time_tolerance_s=5.0,
        spec_generator=SpectrogramGenerator(
            n_fft=4096,
            hop_length=256,
            min_freq_hz=90.0,
            max_freq_hz=150.0,
        ),
    )

    result = pipeline.run(
        adsb_parquet_path=env["parquet_path"],
        measurement_config=env["config"],
        search_bbox=env["bbox"],
        audio_path_or_spec=env["audio_path"],
        output_dir=out_dir,
        top_k=3,
    )

    # 1. Coarse matches found
    assert result.coarse_matches_count > 0

    # 2. Top candidates returned
    assert len(result.top_candidates) == 3
    top1 = result.top_candidates[0]
    assert top1.rank == 1
    assert top1.flight_id_1 == "N172_E1"
    assert top1.flight_id_2 == "PA28_E2"

    # 3. Spatial accuracy: candidate location must be within 100 meters of ground truth!
    from doppler_geo.coordinates import horizontal_haversine_distance
    distance_error = horizontal_haversine_distance(top1.lat, top1.lon, env["true_lat"], env["true_lon"])
    assert distance_error <= 100.0  # Less than 100 meters error!

    # 4. Verify output files exist and are populated
    assert os.path.exists(result.geojson_path)
    assert os.path.getsize(result.geojson_path) > 500

    assert os.path.exists(result.map_html_path)
    assert os.path.getsize(result.map_html_path) > 1000

    assert os.path.exists(result.plot_path)
    assert os.path.getsize(result.plot_path) > 10000

